-- No contiene DROP/TRUNCATE y no debe ejecutarse con las credenciales de runtime.

CREATE TABLE ROLES (
    ID_ROL NUMBER(10) NOT NULL,
    NOMBRE VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE RUBROS_EMPRESA (
    ID_RUBRO NUMBER(10) NOT NULL,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_RUBROS_EMPRESA PRIMARY KEY (ID_RUBRO),
    CONSTRAINT UQ_RUBROS_EMPRESA_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE TIPOS_EMPRESA (
    ID_TIPO NUMBER(10) NOT NULL,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_TIPOS_EMPRESA PRIMARY KEY (ID_TIPO),
    CONSTRAINT UQ_TIPOS_EMPRESA_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIOS (
    ID_USUARIO VARCHAR2(36 CHAR) NOT NULL,
    ID_ROL NUMBER(10) NOT NULL,
    CORREO VARCHAR2(255 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    ESTADO_VALIDACION VARCHAR2(50 CHAR) DEFAULT 'Pendiente' NOT NULL,
    FECHA_CREACION TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    FECHA_ELIMINACION TIMESTAMP(6) NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIOS_CORREO UNIQUE (CORREO),
    CONSTRAINT FK_USUARIOS_ROLES FOREIGN KEY (ID_ROL) REFERENCES ROLES (ID_ROL),
    CONSTRAINT CK_USUARIOS_ESTADO CHECK (
        ESTADO_VALIDACION IN ('Pendiente', 'Aprobado', 'Rechazado', 'Suspendido')
    )
);

CREATE TABLE EMPRESAS (
    ID_EMPRESA VARCHAR2(36 CHAR) NOT NULL,
    RUT_EMPRESA VARCHAR2(20 CHAR) NOT NULL,
    NOMBRE_EMPRESA VARCHAR2(255 CHAR) NOT NULL,
    ID_RUBRO NUMBER(10) NOT NULL,
    ID_TIPO_EMPRESA NUMBER(10) NOT NULL,
    PRESENTACION CLOB NULL,
    BENEFICIOS CLOB NULL,
    LOGO_URL VARCHAR2(255 CHAR) NULL,
    FECHA_CREACION TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    FECHA_ELIMINACION TIMESTAMP(6) NULL,
    CONSTRAINT PK_EMPRESAS PRIMARY KEY (ID_EMPRESA),
    CONSTRAINT UQ_EMPRESAS_RUT UNIQUE (RUT_EMPRESA),
    CONSTRAINT FK_EMPRESAS_RUBROS FOREIGN KEY (ID_RUBRO) REFERENCES RUBROS_EMPRESA (ID_RUBRO),
    CONSTRAINT FK_EMPRESAS_TIPOS FOREIGN KEY (ID_TIPO_EMPRESA) REFERENCES TIPOS_EMPRESA (ID_TIPO)
);

CREATE TABLE USUARIOS_EMPRESA (
    ID_USUARIO VARCHAR2(36 CHAR) NOT NULL,
    ID_EMPRESA VARCHAR2(36 CHAR) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(255 CHAR) NOT NULL,
    TELEFONO_CONTACTO VARCHAR2(20 CHAR) NULL,
    CONSTRAINT PK_USUARIOS_EMPRESA PRIMARY KEY (ID_USUARIO),
    CONSTRAINT FK_USUARIOS_EMPRESA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_USUARIOS_EMPRESA_EMPRESA FOREIGN KEY (ID_EMPRESA)
        REFERENCES EMPRESAS (ID_EMPRESA) ON DELETE CASCADE
);

