CREATE TABLE SOLICITUDES_TALENTO (
    ID_SOLICITUD VARCHAR2(36 CHAR) NOT NULL,
    ID_EMPRESA VARCHAR2(36 CHAR) NOT NULL,
    ID_TALENTO VARCHAR2(36 CHAR) NOT NULL,
    ID_ESTADO NUMBER(10) NOT NULL,
    NOTAS_INTERNAS CLOB NULL,
    FECHA_SOLICITUD TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_SOLICITUDES_TALENTO PRIMARY KEY (ID_SOLICITUD),
    CONSTRAINT FK_SOLICITUDES_EMPRESA FOREIGN KEY (ID_EMPRESA)
        REFERENCES EMPRESAS (ID_EMPRESA) ON DELETE CASCADE,
    CONSTRAINT FK_SOLICITUDES_TALENTO FOREIGN KEY (ID_TALENTO)
        REFERENCES TALENTOS (ID_TALENTO) ON DELETE CASCADE,
    CONSTRAINT FK_SOLICITUDES_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES ESTADOS_SEGUIMIENTO (ID_ESTADO)
);

CREATE INDEX IX_SOLICITUDES_EMPRESA_FECHA
