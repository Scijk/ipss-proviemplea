-- Perfil de talento, certificado de residencia y flujo inicial de selección.
-- Requiere que 001-authentication.sql ya se haya aplicado en el esquema.

CREATE TABLE TALENTOS (
    ID_TALENTO VARCHAR2(36 CHAR) NOT NULL,
    ID_USUARIO VARCHAR2(36 CHAR) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(200 CHAR) NOT NULL,
    RUT VARCHAR2(12 CHAR) NOT NULL,
    TELEFONO VARCHAR2(20 CHAR) NOT NULL,
    RESUMEN VARCHAR2(2000 CHAR) NULL,
    FECHA_CREACION TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    FECHA_ELIMINACION TIMESTAMP(6) NULL,
    CONSTRAINT PK_TALENTOS PRIMARY KEY (ID_TALENTO),
    CONSTRAINT UQ_TALENTOS_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UQ_TALENTOS_RUT UNIQUE (RUT),
    CONSTRAINT FK_TALENTOS_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE
);

CREATE TABLE ANTECEDENTES_LABORALES (
    ID_LABORAL VARCHAR2(36 CHAR) NOT NULL,
    ID_TALENTO VARCHAR2(36 CHAR) NOT NULL,
    EMPRESA VARCHAR2(150 CHAR) NOT NULL,
    CARGO VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPCION CLOB NULL,
    FECHA_INICIO DATE NULL,
    FECHA_FIN DATE NULL,
    FECHA_ELIMINACION TIMESTAMP(6) NULL,
    CONSTRAINT PK_ANTECEDENTES_LABORALES PRIMARY KEY (ID_LABORAL),
    CONSTRAINT FK_LABORALES_TALENTO FOREIGN KEY (ID_TALENTO)
        REFERENCES TALENTOS (ID_TALENTO) ON DELETE CASCADE,
    CONSTRAINT CK_LABORALES_FECHAS CHECK (
        FECHA_INICIO IS NULL OR FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO
    )
);

CREATE TABLE ARCHIVOS_TALENTO (
    ID_ARCHIVO VARCHAR2(36 CHAR) NOT NULL,
    ID_TALENTO VARCHAR2(36 CHAR) NOT NULL,
    TIPO_DOCUMENTO VARCHAR2(50 CHAR) NOT NULL,
    FORMATO VARCHAR2(10 CHAR) NOT NULL,
    TIPO_CONTENIDO VARCHAR2(100 CHAR) NOT NULL,
    CLAVE_ALMACENAMIENTO VARCHAR2(80 CHAR) NOT NULL,
    TAMANO_BYTES NUMBER(19) NOT NULL,
    FECHA_SUBIDA TIMESTAMP(6) NOT NULL,
    FECHA_ELIMINACION TIMESTAMP(6) NULL,
    CONSTRAINT PK_ARCHIVOS_TALENTO PRIMARY KEY (ID_ARCHIVO),
    CONSTRAINT FK_ARCHIVOS_TALENTO FOREIGN KEY (ID_TALENTO)
        REFERENCES TALENTOS (ID_TALENTO) ON DELETE CASCADE,
    CONSTRAINT CK_ARCHIVOS_TIPO CHECK (TIPO_DOCUMENTO = 'comprobante_residencia'),
    CONSTRAINT CK_ARCHIVOS_TAMANO CHECK (TAMANO_BYTES BETWEEN 1 AND 5242880)
);

CREATE INDEX IX_ARCHIVOS_TALENTO_FECHA
    ON ARCHIVOS_TALENTO (ID_TALENTO, TIPO_DOCUMENTO, FECHA_SUBIDA);

CREATE TABLE ESTADOS_SEGUIMIENTO (
    ID_ESTADO NUMBER(10) NOT NULL,
    NOMBRE VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT PK_ESTADOS_SEGUIMIENTO PRIMARY KEY (ID_ESTADO),
    CONSTRAINT UQ_ESTADOS_SEGUIMIENTO_NOMBRE UNIQUE (NOMBRE)
);

